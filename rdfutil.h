// ============================================================================
// GenParticle selection utilities (NanoAOD GenPart_* collection)
//
// Goal
//  1) Build a mask selecting particles that correspond (as closely as NanoAOD allows)
//     to the LHE hard-process record.
//  2) If a selected hard-process particle is W/Z/H/top/tau, also keep its full
//     decay tree as generated by Pythia (i.e. descendants), so you can read
//     W->cs, Z->bb, H->WW->..., H->ZZ->..., top->bW->..., tau decays, etc.
//  3) Return an RVec<bool> mask suitable for TrimCollection(..., maskCol, ...).
//
// Notes / assumptions
//  - NanoAOD does not store the LHE event record in GenPart; this uses GenPart
//    statusFlags to approximate "particles that would have been in LHE":
//      fromHardProcessBeforeFSR && isFirstCopy
//  - You can tune the "LHE-like" seed definition as needed.
// ============================================================================

inline auto gen_mask = [](const ROOT::VecOps::RVec<int>& pdgId,
                          const ROOT::VecOps::RVec<int>& status,
                          const ROOT::VecOps::RVec<int>& statusFlags,
                          const ROOT::VecOps::RVec<int>& genPartIdxMother) -> ROOT::VecOps::RVec<bool>
{
    using ROOT::VecOps::RVec;

    const size_t n = pdgId.size();
    RVec<bool> keep(n, false);
    if (n == 0) return keep;

    // status flags bit reader
    auto testBit = [](int flags, unsigned bit) -> bool {
        return (flags >> bit) & 0x1;
    };

    for (size_t i = 0; i < n; ++i)
    {
        const int s = status[i];
        const int p = pdgId[i];
        const int f = statusFlags[i];
        if (testBit(f, 7) and abs(p) <= 25) keep[i] = true;
        // std::cout <<  " s: " << s <<  " p: " << p <<  std::endl;
        // if (s == 21) keep[i] = true;
        // if (s == 23 and (abs(p) >= 11 and abs(p) <= 16)) keep[i] = true;
        // if (s == 23 and (abs(p) >= 1 and abs(p) <= 5)) keep[i] = true;
        // if (testBit(f, 8) and abs(p) <= 25) keep[i] = true;
        // if (s == 52) keep[i] = true;
        // keep[i] = true;
    }

    return keep;

};

